"""
Router Accuracy & Latency Benchmark for the Agentic RAG System.

What this measures:
- Routing accuracy: Does the LLM router correctly classify each query type?
- Per-category accuracy: Which query categories are hardest to classify?
- Latency: How long does each routing decision take (pure LLM API call time)?

What this does NOT measure:
- Retrieval quality (requires indexed documents — run the app and upload files)
- Answer accuracy (subjective; requires human evaluation)
- End-to-end latency (run the full pipeline via the app)

Usage:
    cd <project_root>
    python eval/benchmark.py

Output:
    eval/results.md  — formatted Markdown table with all results
"""

import json
import sys
import os
import time
from pathlib import Path

# Force UTF-8 output on Windows (avoids cp1252 UnicodeEncodeError)
os.environ.setdefault("PYTHONIOENCODING", "utf-8")
if sys.stdout.encoding and sys.stdout.encoding.lower() != "utf-8":
    sys.stdout.reconfigure(encoding="utf-8")
# Add project root to sys.path so backend imports work
sys.path.insert(0, str(Path(__file__).parent.parent))

from dotenv import load_dotenv
load_dotenv()

from backend.llm import get_llm
from backend.router import route_query

QUESTIONS_FILE = Path(__file__).parent / "sample_questions.json"
RESULTS_FILE   = Path(__file__).parent / "results.md"


def run_benchmark():
    print("=" * 60)
    print("  Agentic RAG — Router Benchmark")
    print("=" * 60)

    with open(QUESTIONS_FILE) as f:
        questions = json.load(f)

    print(f"\nLoading LLM (Groq)...")
    llm = get_llm()
    print(f"Running {len(questions)} questions...\n")

    results = []
    correct = 0

    for q in questions:
        qid      = q["id"]
        question = q["question"]
        expected = q["expected_strategy"]
        category = q["category"]

        print(f"  [{qid:02d}/20] {question[:55]:<55}", end="", flush=True)

        t = time.time()
        try:
            decision      = route_query(question, llm, [])   # No docs indexed
            actual        = decision["strategy"]
            latency       = round(time.time() - t, 2)
            is_correct    = actual == expected
            if is_correct:
                correct += 1
            status = "OK" if is_correct else "FAIL"
            print(f"  [{status}]  {actual:<18}  {latency}s")
        except Exception as exc:
            latency    = -1
            actual     = "ERROR"
            is_correct = False
            print(f"  [FAIL]  ERROR: {exc}")

        results.append({
            "id":        qid,
            "question":  question,
            "category":  category,
            "expected":  expected,
            "actual":    actual,
            "correct":   is_correct,
            "latency_s": latency,
        })

    # ── Summary ───────────────────────────────────────────────────────────────
    accuracy = correct / len(questions) * 100
    valid_latencies = [r["latency_s"] for r in results if r["latency_s"] >= 0]
    avg_latency = sum(valid_latencies) / max(1, len(valid_latencies))

    # Per-category stats
    categories: dict = {}
    for r in results:
        cat = r["category"]
        categories.setdefault(cat, {"correct": 0, "total": 0, "latencies": []})
        categories[cat]["total"] += 1
        if r["correct"]:
            categories[cat]["correct"] += 1
        if r["latency_s"] >= 0:
            categories[cat]["latencies"].append(r["latency_s"])

    print("\n" + "=" * 60)
    print(f"  Routing Accuracy : {accuracy:.0f}%  ({correct}/{len(questions)})")
    print(f"  Average Latency  : {avg_latency:.2f}s per query")
    print("=" * 60)

    _write_results(results, accuracy, avg_latency, categories, correct, len(questions))
    print(f"\n📄 Full results written to: {RESULTS_FILE}\n")


def _write_results(results, accuracy, avg_latency, categories, correct, total):
    from backend import config

    lines = [
        "# Benchmark Results — Router Accuracy & Latency",
        "",
        f"> Generated by `eval/benchmark.py`  |  Model: `{config.LLM_MODEL}` (Groq)",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| **Routing Accuracy** | **{accuracy:.0f}%** ({correct}/{total} correct) |",
        f"| **Average Latency** | **{avg_latency:.2f}s** per routing decision |",
        f"| **LLM Model** | `{config.LLM_MODEL}` |",
        f"| **Test Set** | {total} questions across {len(categories)} categories |",
        "",
        "## Per-Category Breakdown",
        "",
        "| Category | Accuracy | Avg Latency | Questions |",
        "|---|---|---|---|",
    ]

    for cat, data in sorted(categories.items()):
        cat_acc = data["correct"] / data["total"] * 100
        cat_lat = sum(data["latencies"]) / max(1, len(data["latencies"]))
        lines.append(
            f"| `{cat}` | {cat_acc:.0f}% ({data['correct']}/{data['total']}) "
            f"| {cat_lat:.2f}s | {data['total']} |"
        )

    lines += [
        "",
        "## Detailed Results",
        "",
        "| # | Category | Question | Expected | Actual | ✓/✗ | Latency |",
        "|---|---|---|---|---|---|---|",
    ]

    for r in results:
        q_short = r["question"][:50] + ("..." if len(r["question"]) > 50 else "")
        check   = "✅" if r["correct"] else "❌"
        lat     = f"{r['latency_s']}s" if r["latency_s"] >= 0 else "ERROR"
        lines.append(
            f"| {r['id']} | `{r['category']}` | {q_short} "
            f"| `{r['expected']}` | `{r['actual']}` | {check} | {lat} |"
        )

    lines += [
        "",
        "## Notes",
        "",
        "- Benchmark tests **routing accuracy only** (no documents indexed during the run).",
        "- `all_docs` and `targeted_search` queries with no indexed sources may occasionally",
        "  be routed to `llm_knowledge` — these are counted as **incorrect** to maintain strictness.",
        "- Latency reflects the LLM API call time only (no embedding or Qdrant search).",
        "- To benchmark retrieval quality, upload a test document via the app and evaluate",
        "  answer correctness manually against known ground-truth answers.",
    ]

    RESULTS_FILE.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    run_benchmark()
